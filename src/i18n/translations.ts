// Helper to translate default category names
export function getLocalizedCategoryName(categoryName: string, lang: Language): string {
  if (!categoryName) return categoryName;
  const lower = categoryName.toLowerCase();
  const dict = translations[lang].categories;

  if (lower.includes('operasional') || lower.includes('operational')) return dict.officeOperational;
  if (lower.includes('pantry') || lower.includes('konsumsi')) return dict.pantryConsumption;
  if (lower.includes('fasilitas') || lower.includes('utilitas') || lower.includes('facility')) return dict.facilityUtility;
  if (lower.includes('transport') || lower.includes('perjalanan')) return dict.transportTravel;
  if (lower.includes('teknologi') || lower.includes('software') || lower.includes('tech')) return dict.technologySoftware;
  if (lower.includes('pemasaran') || lower.includes('iklan') || lower.includes('marketing')) return dict.marketingAds;
  if (lower.includes('kesehatan') || lower.includes('keselamatan') || lower.includes('health')) return dict.healthSafety;
  if (lower.includes('lain')) return dict.miscellaneous;

  return categoryName;
}

// Helper to translate month labels (e.g. '2026-08' -> 'Agustus 2026' / 'August 2026')
export function getLocalizedMonthLabel(monthKey: string, lang: Language): string {
  if (!monthKey || monthKey === 'all') {
    return translations[lang].months.allData;
  }
  const [year, monthStr] = monthKey.split('-');
  const monthNum = parseInt(monthStr, 10);
  const monthKeys = [
    'january', 'february', 'march', 'april', 'may', 'june',
    'july', 'august', 'september', 'october', 'november', 'december',
  ] as const;

  const key = monthKeys[monthNum - 1];
  if (!key) return monthKey;

  const monthName = (translations[lang].months as any)[key] || monthKey;
  return `${monthName} ${year}`;
}

// Recursive type to generate dotted keys e.g. "tabs.home"
type NestedKeyOf<ObjectType extends object> = {
  [Key in keyof ObjectType & (string | number)]: ObjectType[Key] extends object
    ? `${Key}.${NestedKeyOf<ObjectType[Key]>}`
    : `${Key}`;
}[keyof ObjectType & (string | number)];

export type TranslationKey = NestedKeyOf<typeof translations.id>;
